export type Locale = keyof typeof messages;

export function errorMessage(error: unknown, locale: Locale, signingIn = false): string {
  const copy = messages[locale];
  if (signingIn && error instanceof ApiError) {
    if (error.status === 401) return copy.wrongPassword;
    if (error.status === 403) return copy.disabledAccount;
  }
  const code = error instanceof ApiError ? error.code : 'REQUEST_ERROR';
  return Object.hasOwn(copy.errors, code)
    ? copy.errors[code as keyof typeof copy.errors]
    : copy.errors.REQUEST_ERROR;
}
